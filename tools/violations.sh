#!/usr/bin/env bash
set -uo pipefail
source "$(dirname "$0")/lib.sh"
OUT="$ROOT/docs/results/c1-consent-cases.md"

CASES=(
  "quorum-met:FINALIZED"
  "quorum-missing:TERMINATED"
  "quorum-one-steward-twice:TERMINATED"
  "purpose-mismatch:TERMINATED"
  "recipient-class-mismatch:TERMINATED"
  "field-outside-grant:TERMINATED"
  "expired-grant-field-excluded:TERMINATED"
  "k-below-threshold:TERMINATED"
  "budget-exceeded:TERMINATED"
)

mkdir -p "$(dirname "$OUT")"
{
  echo "# C1 enforcement correctness, consent cases"
  echo
  echo "Generated by tools/violations.sh. Every row is a real contract negotiation"
  echo "against the connector, not a unit test."
  echo
  echo "A negotiation can terminate for many reasons, so every row also carries the evidence"
  echo "that the outcome came from the constraint this case exists to test."
  echo
  echo "## Scope of the two privacy cases"
  echo
  echo "The \`k-below-threshold\` and \`budget-exceeded\` cases exercise \`KAnonymityFunction\` and"
  echo "\`EpsilonBudgetFunction\` against a directly-seeded \`ReleaseArtifact\`, not one produced by"
  echo "a live \`PrivacyPipeline\` run. \`tools/run-case.sh\` seeds \`computedK\` and \`epsilonCharged\`"
  echo "values straight into the artifact store; the payload it seeds alongside them"
  echo "(\`{\"groups\":[]}\`) is not a value \`PrivacyPipeline\` could itself produce for those numbers."
  echo "The evidence strings below say \"artifact seeded with computed k\" and \"artifact seeded"
  echo "with epsilon charge\" rather than \"artifact computed k\" or \"artifact charged epsilon\" for"
  echo "this reason."
  echo
  echo "This is a real gap in coverage, not an error in the two cases themselves: the"
  echo "connector-side enforcement point (the constraint functions reading a stored artifact and"
  echo "comparing it against policy) is proven correct here, on artifacts whose values are chosen"
  echo "to land on each side of the policy threshold. What is not yet proven end to end is that a"
  echo "live \`PrivacyPipeline.compute\` run, wired into a real release-request-creation path, would"
  echo "itself produce an artifact whose \`computedK\` and \`epsilonCharged\` match what the pipeline"
  echo "actually computed from real contributions. That path does not exist yet in this phase."
  echo
  echo "The pipeline's own correctness is proven separately, by code that does run it:"
  echo "\`PrivacyPipelineTest\` exercises \`PrivacyPipeline.compute\` end to end; \`KAnonymityTest\`"
  echo "proves the grouping and suppression behaviour \`PrivacyPipeline\` composes; and"
  echo "\`LaplaceNoiseSourceTest\` proves the noise source it composes. \`InMemoryBudgetAccountantTest\`"
  echo "proves the budget accountant's reservation is atomic. Wiring \`PrivacyPipeline\` into a live"
  echo "release-request-creation path, so the connector's negotiation-time enforcement operates on"
  echo "artifacts the pipeline actually computed rather than ones seeded by test tooling, is not"
  echo "done in this phase and is a natural next step."
  echo
  echo "| Case | Expected | Observed | Pass | Evidence |"
  echo "|---|---|---|---|---|"
} > "$OUT"

failed=0
for entry in "${CASES[@]}"; do
  name=${entry%%:*}
  expected=${entry##*:}
  rm -f /tmp/negotiation.json
  observed=$("$ROOT/tools/run-case.sh" "$name" | tail -1)
  cp /tmp/provider.log "/tmp/provider-$name.log" 2>/dev/null || true
  cp /tmp/consumer.log "/tmp/consumer-$name.log" 2>/dev/null || true
  cp /tmp/negotiation.json "/tmp/negotiation-$name.json" 2>/dev/null || true
  cp /tmp/benefits-case/policy.json "/tmp/policy-$name.json" 2>/dev/null || true
  cp /tmp/benefits-case/consumer.properties "/tmp/consumer-$name.properties" 2>/dev/null || true
  cp /tmp/benefits-case/artifacts.json "/tmp/artifacts-$name.json" 2>/dev/null || true
  if evidence=$(verify_cause "$name"); then cause=yes; else cause=no; failed=1; fi
  if [ "$observed" = "$expected" ] && [ "$cause" = yes ]; then pass=yes; else pass=no; failed=1; fi
  echo "| $name | $expected | $observed | $pass | $evidence |" >> "$OUT"
done

cat "$OUT"
exit $failed
