#!/usr/bin/env bash
set -uo pipefail
source "$(dirname "$0")/lib.sh"
OUT="$ROOT/docs/results/c1-consent-cases.md"

CASES=(
  "quorum-met:FINALIZED"
  "quorum-missing:TERMINATED"
  "quorum-one-steward-twice:TERMINATED"
  "purpose-mismatch:TERMINATED"
  "recipient-class-mismatch:TERMINATED"
  "field-outside-grant:TERMINATED"
  "expired-grant-field-excluded:TERMINATED"
)

mkdir -p "$(dirname "$OUT")"
{
  echo "# C1 enforcement correctness, consent cases"
  echo
  echo "Generated by tools/violations.sh. Every row is a real contract negotiation"
  echo "against the connector, not a unit test."
  echo
  echo "A negotiation can terminate for many reasons, so every row also carries the evidence"
  echo "that the outcome came from the constraint this case exists to test."
  echo
  echo "| Case | Expected | Observed | Pass | Evidence |"
  echo "|---|---|---|---|---|"
} > "$OUT"

failed=0
for entry in "${CASES[@]}"; do
  name=${entry%%:*}
  expected=${entry##*:}
  rm -f /tmp/negotiation.json
  observed=$("$ROOT/tools/run-case.sh" "$name" | tail -1)
  cp /tmp/provider.log "/tmp/provider-$name.log" 2>/dev/null || true
  cp /tmp/consumer.log "/tmp/consumer-$name.log" 2>/dev/null || true
  cp /tmp/negotiation.json "/tmp/negotiation-$name.json" 2>/dev/null || true
  cp /tmp/benefits-case/policy.json "/tmp/policy-$name.json" 2>/dev/null || true
  cp /tmp/benefits-case/consumer.properties "/tmp/consumer-$name.properties" 2>/dev/null || true
  if evidence=$(verify_cause "$name"); then cause=yes; else cause=no; failed=1; fi
  if [ "$observed" = "$expected" ] && [ "$cause" = yes ]; then pass=yes; else pass=no; failed=1; fi
  echo "| $name | $expected | $observed | $pass | $evidence |" >> "$OUT"
done

cat "$OUT"
exit $failed
